from statistics import mean
def agg(rows):
    return {
        "n": len(rows),
        "reach_med": round(mean(r[1] for r in rows)),
        "likes_med": round(mean(r[2] for r in rows),1),
        "saves_tot": sum(r[4] for r in rows),
        "views_med": round(mean(r[5] for r in rows)),
    }

